"""Interactive local integration setup. Secret values are never printed."""
import argparse
from getpass import getpass
from pathlib import Path
from dotenv import dotenv_values,set_key,load_dotenv
from pydantic import TypeAdapter,EmailStr,ValidationError

ENV=Path(__file__).resolve().parent/'.env'
LOCAL_ORIGIN='http://localhost:5173'


def put(key,value):
    set_key(ENV,key,value,quote_mode='always')


def email_value(value):
    try:return str(TypeAdapter(EmailStr).validate_python(value))
    except ValidationError:raise SystemExit('Enter a valid email address.')


def configure_provider(provider):
    client=input(f'{provider.title()} client ID: ').strip()
    secret=getpass(f'{provider.title()} client secret (hidden): ').strip()
    if not client or not secret:raise SystemExit('Both fields are required. No provider settings were changed.')
    put(provider.upper()+'_CLIENT_ID',client)
    put(provider.upper()+'_CLIENT_SECRET',secret)
    put('PUBLIC_BASE_URL',LOCAL_ORIGIN);put('FRONTEND_URL',LOCAL_ORIGIN)
    print(f'{provider.title()} credentials saved locally. Restart the backend to load them.')


def configure_gmail():
    sender=email_value(input('Gmail address to send from: ').strip())
    password=''.join(getpass('Gmail App Password (hidden, 16 characters): ').split())
    if len(password)!=16:raise SystemExit('Use the 16-character App Password generated by Google. No email settings were changed.')
    for key,value in {'SMTP_HOST':'smtp.gmail.com','SMTP_PORT':'587','SMTP_EMAIL':sender,'SMTP_APP_PASSWORD':password,'FRONTEND_URL':LOCAL_ORIGIN}.items():put(key,value)
    print('Gmail settings saved locally. No email was sent.')


def check():
    values=dotenv_values(ENV)
    for provider in ('GOOGLE','GITHUB'):
        ready=bool(values.get(provider+'_CLIENT_ID') and values.get(provider+'_CLIENT_SECRET'))
        print(provider+': '+('credentials present (live authorization still needs checking)' if ready else 'credentials needed'))
    present=bool(values.get('SMTP_EMAIL') and values.get('SMTP_APP_PASSWORD'))
    gmail_format=len(''.join((values.get('SMTP_APP_PASSWORD') or '').split()))==16
    print('Gmail: '+('App Password format is ready for a delivery test' if present and gmail_format else 'set the sender and a valid 16-character App Password'))
    for provider in ('google','github'):print(provider.title()+' callback: '+LOCAL_ORIGIN+f'/api/auth/oauth/{provider}/callback')


def test_email(recipient):
    recipient=email_value(recipient)
    values=dotenv_values(ENV)
    if values.get('SMTP_HOST','smtp.gmail.com')=='smtp.gmail.com' and len(''.join((values.get('SMTP_APP_PASSWORD') or '').split()))!=16:
        raise SystemExit('Set a 16-character Gmail App Password first with --gmail. No email sent.')
    load_dotenv(ENV,override=True)
    from email_service import send_email
    try:
        send_email(recipient,'CareerNova email delivery test','This is the single CareerNova test notification you requested.\n\nIf you received it, SMTP delivery is working. Job digests also require a verified account, notification opt-in, an alert rule and the running alert worker.\n\nCareerNova AI')
    except Exception as exc:
        raise SystemExit('Delivery test failed ('+type(exc).__name__+'). No success was confirmed. Check the Gmail App Password and network connection.')
    print('SMTP accepted the test message. Please check the recipient inbox and spam folder.')


if __name__=='__main__':
    parser=argparse.ArgumentParser(description='Configure CareerNova integrations locally without exposing secrets in chat.')
    group=parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--oauth',choices=['google','github'])
    group.add_argument('--gmail',action='store_true')
    group.add_argument('--check',action='store_true')
    group.add_argument('--test-email',metavar='ADDRESS')
    args=parser.parse_args()
    if args.oauth:configure_provider(args.oauth)
    elif args.gmail:configure_gmail()
    elif args.test_email:test_email(args.test_email)
    else:check()
